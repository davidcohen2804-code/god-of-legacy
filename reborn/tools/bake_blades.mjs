// GOD OF LEGACY — REBORN: bakes each sword attack's blade path into data (run with Node + gltf-transform, outside
// Godot; the output is committed). For every attack in data/abilities/samurai.json it poses the Samurai's move
// through the attack's active window exactly as the game plays it (the move started at anim_from, played at
// anim_speed) and records the katana's blade — a point near the guard and the tip — at 13 evenly spaced moments, in
// the character's own frame (+Z forward, +X his left, +Y up, origin between his feet). The game's hit test sweeps
// the blade between those positions (scripts/combat/sword_sweep.gd), so the hit follows the visible swing; a Godot
// test checks the baked path against the move as Godot plays it.
// Usage: node bake_blades.mjs <samurai.glb> <grip.json> <abilities.json> <out blades.json>
import { NodeIO } from '@gltf-transform/core';
import fs from 'node:fs';

const [GLB, GRIP, ABILITIES, OUT] = process.argv.slice(2);
const SAMPLES = 13;
const BASE_Y = 0.12; // along the blade from the grip's origin (the guard is at 0.03)
const doc = await new NodeIO().read(GLB);
const grip = JSON.parse(fs.readFileSync(GRIP, 'utf8'));
const abilities = JSON.parse(fs.readFileSync(ABILITIES, 'utf8'));
const root = doc.getRoot();
const parent = new Map();
for (const n of root.listNodes()) for (const c of n.listChildren()) parent.set(c, n);
const byName = new Map(root.listNodes().map((n) => [n.getName(), n]));

const qrot = (q, v) => { const [x, y, z, w] = q; const uv = [y*v[2]-z*v[1], z*v[0]-x*v[2], x*v[1]-y*v[0]]; const uuv = [y*uv[2]-z*uv[1], z*uv[0]-x*uv[2], x*uv[1]-y*uv[0]]; return [v[0]+2*(w*uv[0]+uuv[0]), v[1]+2*(w*uv[1]+uuv[1]), v[2]+2*(w*uv[2]+uuv[2])]; };
const slerp = (a, b, t) => { let d = a[0]*b[0]+a[1]*b[1]+a[2]*b[2]+a[3]*b[3]; let bb = b; if (d < 0) { d = -d; bb = b.map((x) => -x); } if (d > 0.9995) { const r = a.map((x, i) => x + (bb[i]-x)*t); const l = Math.hypot(...r); return r.map((x) => x/l); } const th = Math.acos(d), s = Math.sin(th); const wa = Math.sin((1-t)*th)/s, wb = Math.sin(t*th)/s; return a.map((x, i) => wa*x + wb*bb[i]); };
const sample = (sampler, t, comps) => {
  const inp = sampler.getInput().getArray(), out = sampler.getOutput().getArray();
  if (t <= inp[0]) return Array.from(out.slice(0, comps));
  if (t >= inp[inp.length - 1]) return Array.from(out.slice((inp.length - 1) * comps, inp.length * comps));
  let i = 0; while (inp[i + 1] < t) i++;
  const k = (t - inp[i]) / (inp[i + 1] - inp[i]);
  const a = Array.from(out.slice(i * comps, (i + 1) * comps)), b = Array.from(out.slice((i + 1) * comps, (i + 2) * comps));
  return comps === 4 ? slerp(a, b, k) : a.map((x, j) => x + (b[j] - x) * k);
};
const chainTo = (n) => { const c = []; let x = n; while (x) { c.unshift(x); x = parent.get(x); } return c; };
const handChain = chainTo(byName.get('hand_r'));
const along = (y) => [grip.position[0] + grip.basis.y[0] * y, grip.position[1] + grip.basis.y[1] * y, grip.position[2] + grip.basis.y[2] * y];
const BASE = along(BASE_Y), TIP = along(grip.y1);
const r3 = (p) => p.map((x) => Math.round(x * 1000) / 1000);

const out = { _doc: 'Generated by tools/bake_blades.mjs from samurai.glb and data/abilities/samurai.json — do not edit by hand.',
  base_along: BASE_Y, tip_along: Math.round(grip.y1 * 1000) / 1000, samples: SAMPLES, attacks: {} };
for (const [id, a] of Object.entries(abilities.attacks)) {
  const anim = root.listAnimations().find((x) => x.getName() === a.anim);
  if (!anim) throw new Error(`${id}: no move ${a.anim}`);
  const ch = new Map();
  for (const c of anim.listChannels()) ch.set(c.getTargetNode().getName() + '/' + c.getTargetPath(), c.getSampler());
  const world = (t, local) => {
    let p = local;
    for (let i = handChain.length - 1; i >= 0; i--) {
      const n = handChain[i];
      const r = ch.has(n.getName() + '/rotation') ? sample(ch.get(n.getName() + '/rotation'), t, 4) : n.getRotation();
      const tr = ch.has(n.getName() + '/translation') ? sample(ch.get(n.getName() + '/translation'), t, 3) : n.getTranslation();
      const sc = n.getScale();
      p = qrot(r, [p[0] * sc[0], p[1] * sc[1], p[2] * sc[2]]);
      p = [p[0] + tr[0], p[1] + tr[1], p[2] + tr[2]];
    }
    return p;
  };
  const base = [], tip = [];
  for (let i = 0; i < SAMPLES; i++) {
    const f = i / (SAMPLES - 1);
    const t = a.anim_from + (a.startup + f * a.active) * a.anim_speed;
    base.push(r3(world(t, BASE)));
    tip.push(r3(world(t, TIP)));
  }
  const yaw = (p) => Math.round(Math.atan2(p[0], p[2]) * 180 / Math.PI);
  const reach = Math.max(...tip.map((p) => Math.hypot(p[0], p[2])));
  out.attacks[id] = { anim: a.anim, from_s: +(a.anim_from + a.startup * a.anim_speed).toFixed(3),
    to_s: +(a.anim_from + (a.startup + a.active) * a.anim_speed).toFixed(3), base, tip };
  console.log(`${id}: ${a.anim} ${out.attacks[id].from_s}–${out.attacks[id].to_s} s, tip yaw ${tip.map(yaw).join(' ')}, reach ${reach.toFixed(2)} m, tip height ${Math.min(...tip.map((p) => p[1])).toFixed(2)}–${Math.max(...tip.map((p) => p[1])).toFixed(2)} m`);
}
// (one point per line: readable, and diffs stay small)
fs.writeFileSync(OUT, JSON.stringify(out, null, 1).replace(/\[\s+(-?[\d.]+),\s+(-?[\d.]+),\s+(-?[\d.]+)\s+\]/g, '[$1, $2, $3]') + '\n');
